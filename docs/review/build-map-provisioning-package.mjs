// Offline artifact generator. Never connects to a database or reads environment credentials.
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { createHash } from 'node:crypto';

const root = new URL('./map-provisioning/', import.meta.url);
const draft = await readFile(new URL('./map-store-schema.sql', import.meta.url), 'utf8');
const sourceHash = createHash('sha256').update(draft).digest('hex');
const start = draft.indexOf('REVOKE ALL ON SCHEMA mi_map_private FROM PUBLIC;');
const end = draft.lastIndexOf('COMMIT;');
if (start < 0 || end < start) throw new Error('Unexpected source draft boundary');
const names = ['mi_map_owner', 'mi_map_reader', 'mi_map_access_writer', 'mi_map_ingester',
    'mi_map_reader_login', 'mi_map_access_login'];
const options = 'NOLOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS';
const sql = `-- SCOPED REVIEW CANDIDATE ONLY: Investscape-Dev hwhkgrwikczwztfnsjir.
-- Not applied. This file is not added to any migration runner.
-- Operator must approve owner/ledger/recovery and supply a non-secret receipt reference.
-- The receipt guard prevents accidental execution; it is not an authorization mechanism.
-- Initial runtime principals stay NOLOGIN; no password, admin appointment or publication.
-- Generated by build-map-provisioning-package.mjs; source draft SHA256 ${sourceHash}.
BEGIN;
SET LOCAL statement_timeout = '30s';
SET LOCAL lock_timeout = '5s';
DO $$ BEGIN
  IF current_user <> 'postgres' OR NOT EXISTS
    (SELECT 1 FROM pg_roles WHERE rolname=current_user AND rolcreaterole)
    THEN RAISE EXCEPTION 'MAP_PROVISIONING_OPERATOR_MISMATCH'; END IF;
  IF current_setting('server_version_num')::integer < 170000
    THEN RAISE EXCEPTION 'MAP_PROVISIONING_POSTGRES_VERSION'; END IF;
  IF COALESCE(current_setting('mi_map.provisioning_receipt',true),'')
      !~ '^[A-Za-z0-9][A-Za-z0-9._:/-]{7,119}$'
    THEN RAISE EXCEPTION 'MAP_PROVISIONING_RECEIPT_REQUIRED'; END IF;
  IF EXISTS (SELECT 1 FROM pg_namespace WHERE nspname='mi_map_private')
    OR EXISTS (SELECT 1 FROM pg_roles WHERE rolname IN (${names.map(n=>`'${n}'`).join(',')}))
    THEN RAISE EXCEPTION 'MAP_PROVISIONING_NAME_COLLISION'; END IF;
END $$;
-- PostgreSQL grants a non-superuser creator ADMIN automatically. Request SET only for the owner.
-- Do not re-grant ADMIN back to the creator: that forms a prohibited grant cycle.
SET LOCAL createrole_self_grant = 'set';
CREATE ROLE mi_map_owner ${options};
SET LOCAL createrole_self_grant = '';
${names.slice(1).map(n=>`CREATE ROLE ${n} ${options}${n.endsWith('_login') ? ' CONNECTION LIMIT 2' : ''};`).join('\n')}
-- Disposable bootstrap-superuser tests do not receive the automatic creator membership.
DO $$ BEGIN
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname=current_user AND rolsuper) THEN
    GRANT mi_map_owner TO postgres WITH ADMIN TRUE, INHERIT FALSE, SET TRUE;
    GRANT mi_map_reader, mi_map_access_writer, mi_map_ingester,
      mi_map_reader_login, mi_map_access_login TO postgres
      WITH ADMIN TRUE, INHERIT FALSE, SET FALSE;
  END IF;
END $$;
CREATE SCHEMA mi_map_private AUTHORIZATION mi_map_owner;
SET LOCAL ROLE mi_map_owner;
${draft.slice(start,end).trim()}

-- Independent map schema ledger, owned and accessed only by the explicit migration owner.
CREATE TABLE mi_map_private.schema_receipts (
  version text PRIMARY KEY,
  source_ddl_sha256 text NOT NULL CHECK (source_ddl_sha256 ~ '^[a-f0-9]{64}$'),
  receipt_ref text NOT NULL CHECK (length(receipt_ref) BETWEEN 8 AND 120),
  applied_at timestamptz NOT NULL DEFAULT clock_timestamp()
);
ALTER TABLE mi_map_private.schema_receipts ENABLE ROW LEVEL SECURITY;
ALTER TABLE mi_map_private.schema_receipts FORCE ROW LEVEL SECURITY;
CREATE POLICY receipt_owner_read ON mi_map_private.schema_receipts
  FOR SELECT TO mi_map_owner USING (true);
CREATE POLICY receipt_owner_append ON mi_map_private.schema_receipts
  FOR INSERT TO mi_map_owner WITH CHECK (true);
CREATE TRIGGER receipt_immutable BEFORE UPDATE OR DELETE OR TRUNCATE
  ON mi_map_private.schema_receipts FOR EACH STATEMENT
  EXECUTE FUNCTION mi_map_private.deny_mutation();
INSERT INTO mi_map_private.schema_receipts(version,source_ddl_sha256,receipt_ref)
  VALUES ('map-private-v1', '${sourceHash}', current_setting('mi_map.provisioning_receipt'));
-- Final explicit revokes cover the ledger and any GLOBAL defaults; never alter global defaults.
REVOKE ALL ON ALL TABLES IN SCHEMA mi_map_private FROM PUBLIC;
REVOKE ALL ON ALL SEQUENCES IN SCHEMA mi_map_private FROM PUBLIC;
REVOKE ALL ON ALL FUNCTIONS IN SCHEMA mi_map_private FROM PUBLIC;
DO $$ DECLARE r text; BEGIN
  FOREACH r IN ARRAY ARRAY['anon','authenticated','service_role','authenticator'] LOOP
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname=r) THEN
      EXECUTE format('REVOKE ALL ON ALL TABLES IN SCHEMA mi_map_private FROM %I',r);
      EXECUTE format('REVOKE ALL ON ALL SEQUENCES IN SCHEMA mi_map_private FROM %I',r);
      EXECUTE format('REVOKE ALL ON ALL FUNCTIONS IN SCHEMA mi_map_private FROM %I',r);
    END IF;
  END LOOP;
END $$;
RESET ROLE;
GRANT mi_map_reader TO mi_map_reader_login WITH ADMIN FALSE, INHERIT TRUE, SET FALSE;
GRANT mi_map_access_writer TO mi_map_access_login WITH ADMIN FALSE, INHERIT TRUE, SET FALSE;
-- CONNECT applies only to the database being provisioned, never another product database.
DO $$ BEGIN
  EXECUTE format('GRANT CONNECT ON DATABASE %I TO mi_map_reader_login, mi_map_access_login',current_database());
END $$;
-- Assertions stay inside the create transaction. A failure rolls back the entire candidate.
DO $$ BEGIN
  IF EXISTS (SELECT 1 FROM pg_class c JOIN pg_namespace n ON n.oid=c.relnamespace
      WHERE n.nspname='mi_map_private' AND
        (pg_get_userbyid(c.relowner)<>'mi_map_owner' OR
         (c.relkind IN ('r','p') AND (NOT c.relrowsecurity OR NOT c.relforcerowsecurity))))
    OR EXISTS (SELECT 1 FROM pg_proc p JOIN pg_namespace n ON n.oid=p.pronamespace
      WHERE n.nspname='mi_map_private' AND (pg_get_userbyid(p.proowner)<>'mi_map_owner' OR p.prosecdef))
    THEN RAISE EXCEPTION 'MAP_PROVISIONING_OWNER_RLS_MISMATCH'; END IF;
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname IN (${names.map(n=>`'${n}'`).join(',')})
      AND (rolcanlogin OR rolsuper OR rolcreatedb OR rolcreaterole OR rolreplication OR rolbypassrls))
    THEN RAISE EXCEPTION 'MAP_PROVISIONING_ROLE_ATTRIBUTES'; END IF;
  IF EXISTS (SELECT 1 FROM pg_roles r CROSS JOIN pg_namespace n
      WHERE n.nspname='mi_map_private' AND r.rolname IN ('anon','authenticated','service_role','authenticator')
      AND (has_schema_privilege(r.oid,n.oid,'USAGE') OR has_schema_privilege(r.oid,n.oid,'CREATE')))
    OR EXISTS (SELECT 1 FROM pg_roles r CROSS JOIN pg_class c JOIN pg_namespace n ON n.oid=c.relnamespace
      WHERE n.nspname='mi_map_private' AND c.relkind IN ('r','p')
      AND r.rolname IN ('anon','authenticated','service_role','authenticator')
      AND has_table_privilege(r.oid,c.oid,'SELECT,INSERT,UPDATE,DELETE,TRUNCATE,REFERENCES,TRIGGER'))
    OR EXISTS (SELECT 1 FROM pg_roles r CROSS JOIN pg_proc p JOIN pg_namespace n ON n.oid=p.pronamespace
      WHERE n.nspname='mi_map_private' AND r.rolname IN ('anon','authenticated','service_role','authenticator')
      AND has_function_privilege(r.oid,p.oid,'EXECUTE'))
    THEN RAISE EXCEPTION 'MAP_PROVISIONING_GATEWAY_ACCESS'; END IF;
END $$;
COMMIT;
`;
await mkdir(root, { recursive: true });
await writeFile(new URL('001-private-map.review.sql', root), sql);
await writeFile(new URL('package.json', root), JSON.stringify({
    status: 'review-only-not-applied', evidenceDate: '2026-10-09',
    targetProject: { name: 'Investscape-Dev', ref: 'hwhkgrwikczwztfnsjir', postgresMajor: 17 },
    operatorRole: 'postgres', ownerRole: 'mi_map_owner',
    ledger: 'mi_map_private.schema_receipts', version: 'map-private-v1',
    sourceDraftSha256: sourceHash,
    candidateSha256: createHash('sha256').update(sql).digest('hex'),
    roles: names, allNewRolesNoLogin: true, publishedRows: 0, appointedAdmins: 0,
    receiptTemplate: { ownerAuthorizationReference: null, recoveryReference: null,
        effectiveTargetConfirmed: false, appliedAt: null, transactionOutcome: 'not-applied',
        permissionAcceptanceReference: null, credentialBindingReference: null },
}, null, 2) + '\n');
console.log('Generated review SQL and non-secret package manifest; no database was contacted.');
